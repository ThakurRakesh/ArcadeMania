using System.Text.Json;
using ArcadeMania.App.Pages;
using ArcadeMania.App.Services;
using ArcadeMania.Core.Security;

namespace ArcadeMania.App;

public sealed class App : Application
{
    public App()
    {
        // The app must never crash: log and swallow anything that escapes.
        AppDomain.CurrentDomain.UnhandledException += (_, e) => System.Diagnostics.Debug.WriteLine($"Unhandled: {e.ExceptionObject}");
        TaskScheduler.UnobservedTaskException += (_, e) => e.SetObserved();
#if ANDROID
        Android.Runtime.AndroidEnvironment.UnhandledExceptionRaiser += (_, e) => e.Handled = true;
#endif
        try { Theme.Load(); } catch { }
    }

    protected override Window CreateWindow(Microsoft.Maui.IActivationState? activationState)
    {
        var root = new NavigationPage(new PlayPage());
        root.SetDynamicResource(NavigationPage.BarBackgroundColorProperty, "Surface");
        var window = new Window(root) { Title = "ArcadeMania", MinimumWidth = 360, MinimumHeight = 560 };
        window.Created += async (_, _) => await VerifyIntegrityAsync();
        return window;
    }

    /// <summary>Anti-tamper: Release builds ship integrity.json (SHA-256 of every shipped DLL, generated by tools/gen-integrity).
    /// If any file was modified the app refuses to run and exits cleanly — it never deletes or corrupts anything.</summary>
    static async Task VerifyIntegrityAsync()
    {
#if WINDOWS && !DEBUG
        try
        {
            if (!await FileSystem.AppPackageFileExistsAsync("integrity.json")) return;
            await using var s = await FileSystem.OpenAppPackageFileAsync("integrity.json");
            var manifest = await JsonSerializer.DeserializeAsync<Dictionary<string, string>>(s) ?? new();
            var (ok, failed) = IntegrityVerifier.Verify(AppContext.BaseDirectory, manifest);
            if (ok) return;
            var page = Current?.Windows.FirstOrDefault()?.Page;
            if (page is not null) await page.DisplayAlertAsync("ArcadeMania", $"This copy has been modified ({failed}) and cannot run.", "Close");
            AppServices.ExitApp();
        }
        catch { /* missing/unreadable manifest in dev builds → continue */ }
#else
        await Task.CompletedTask;
#endif
    }
}
